## 2.1 read_plant_reference() ----

#' Read One Plant Taxon's Published Climate Coefficients
#'
#' @param taxon Character. Taxon slug.
#' @param dir_path Character. Where the .Rdata files are.
#' @param region Character. Which model set to read: the
#'   vegetation coefficients in the north, the soil ones in the
#'   south.
#' @return A data frame of species, term and the v2 draw summary,
#'   or NULL when the file is absent or unusable.
#'
#' @example # Example usage of the function
#' # read_plant_reference("lichen", reference_paths$plants)
read_plant_reference <- function(taxon, dir_paths, region) {
  # v2 names vascular plants with a hyphen
  file_taxon <- gsub("_", "-", taxon)
  file_name <- paste0(file_taxon, "-species-models.Rdata")

  candidates <- file.path(dir_paths, file_name)
  candidates <- candidates[file.exists(candidates)]

  if (length(candidates) == 0) {
    return(NULL)
  }

  path <- candidates[1]

  env <- new.env()
  load(path, envir = env)

  # The run reports one coefficient set per species: the last
  # stage's. For a plant run that is the habitat stage, so the
  # habitat objects are read, falling back to climate when the
  # reference holds only the climate stage.
  object_name <- switch(
    region,
    north = "vegetation.coef",
    south = "soil.coef",
    "climate.coef"
  )

  if (is.null(env[[object_name]])) {
    object_name <- "climate.coef"
  }

  coefficients <- env[[object_name]]

  if (is.null(coefficients)) {
    return(NULL)
  }

  # A species whose draws all errored comes back list-mode. That
  # is the whole published bryophyte file; see the header.
  usable <- vapply(coefficients, is.numeric, logical(1))

  if (!any(usable)) {
    return(NULL)
  }

  rows <- lapply(names(coefficients)[usable], function(species) {
    draws <- coefficients[[species]]

    # The habitat objects carry a .SE column beside every
    # coefficient; only the estimates are compared.
    terms <- colnames(draws)
    terms <- terms[!grepl("[.]SE$", terms)]

    do.call(rbind, lapply(terms, function(term) {
      values <- draws[, term]
      values <- values[is.finite(values)]

      if (length(values) == 0) {
        return(NULL)
      }

      data.frame(
        species = species,
        term = term,
        v2_median = stats::median(values),
        v2_p10 = stats::quantile(values, 0.1, names = FALSE),
        v2_p90 = stats::quantile(values, 0.9, names = FALSE),
        v2_n = length(values),
        stringsAsFactors = FALSE
      )
    }))
  })

  out <- do.call(rbind, rows)

  if (is.null(out)) {
    return(NULL)
  }

  rownames(out) <- NULL

  # Carried through to parity_climate.csv so a row says what it
  # was measured against. Without this, a habitat run gated
  # against a climate-only reference joins on Intercept alone and
  # reports a parity number for a comparison that never happened.
  out$reference_object <- object_name
  out$reference_source <- path

  out
}

## 2.2 read_mammal_reference() ----

#' Read the Published Mammal Climate Coefficients
#'
#' One model-averaged coefficient per term per species, not a
#' distribution: the v2 mammal climate pipeline does not
#' bootstrap.
#'
#' @param dir_path Character. Where the .RData files are.
#' @return A data frame of species, term and v2_median, or NULL.
#'
#' @example # Example usage of the function
#' # read_mammal_reference(reference_paths$mammals)
read_mammal_reference <- function(dir_path) {
  if (!dir.exists(dir_path)) {
    return(NULL)
  }

  files <- list.files(
    dir_path, pattern = "Climate Coefficients[.]RData$",
    full.names = TRUE
  )

  if (length(files) == 0) {
    return(NULL)
  }

  rows <- lapply(files, function(path) {
    env <- new.env()
    load(path, envir = env)

    if (is.null(env$avg_coef)) {
      return(NULL)
    }

    species <- sub(
      " Climate Coefficients[.]RData$", "", basename(path)
    )

    data.frame(
      species = species,
      term = as.character(env$avg_coef$term),
      v2_median = as.numeric(env$avg_coef$coef),
      v2_p10 = NA_real_,
      v2_p90 = NA_real_,
      v2_n = 1L,
      stringsAsFactors = FALSE
    )
  })

  out <- do.call(rbind, rows)
  rownames(out) <- NULL

  out
}

# 3. Compare ----
# Per term: does the v2 value sit inside this run's draw band,
# and how far apart are the two medians relative to the spread?

parity_rows <- list()
notes <- list()

if (!is.null(run_coefficients)) {
  pairs <- unique(run_coefficients[, c("taxon", "region")])

  for (row in seq_len(nrow(pairs))) {
    taxon <- pairs$taxon[row]
    region <- pairs$region[row]
    label <- paste(taxon, region)

    reference <- if (taxon == "mammal") {
      read_mammal_reference(reference_paths$mammals)
    } else if (taxon == "bird") {
      NULL
    } else {
      read_plant_reference(
        taxon,
        c(reference_paths$plants_local, reference_paths$plants),
        region
      )
    }

    if (is.null(reference)) {
      notes[[label]] <- paste0(
        label, ": no usable v2 reference reachable."
      )
      next
    }

    # A north or south run measured against a climate-only
    # reference is not a habitat comparison. Said out loud here
    # rather than left to be inferred from the term list.
    object_read <- unique(reference$reference_object)

    if (
      region %in% c("north", "south") &&
        identical(object_read, "climate.coef")
    ) {
      notes[[label]] <- paste0(
        label, ": reference holds the climate stage only, so ",
        "habitat terms are uncompared."
      )
    }

    mine <- run_coefficients[
      run_coefficients$taxon == taxon &
        run_coefficients$region == region,
    ]

    # v2 names the intercept without parentheses
    mine$term <- sub("^\\(Intercept\\)$", "Intercept", mine$term)

    joined <- merge(
      mine, reference, by = c("species", "term"), all.x = TRUE
    )

    if (nrow(joined) == 0) {
      notes[[label]] <- paste0(
        label, ": no species and term matched the reference."
      )
      next
    }

    # v2 overwrites the five aged stand types with GAM age
    # splines the harness does not fit, and settles the cutblock
    # age classes 3 and 4 by a convergence step it does not run
    # either. Flagged rather than dropped, so the report can say
    # how much of the difference is the missing machinery.
    joined$age_spline_term <- grepl(
      paste0(
        "^(WhiteSpruce|Pine|Deciduous|Mixedwood|BlackSpruce)",
        "([R1-8])$|^CC.*[34]$"
      ),
      joined$term
    )

    # The v2 value is inside this run's band when it falls
    # between the 10th and 90th percentile of the draws.
    joined$in_band <- with(
      joined,
      is.finite(v2_median) & is.finite(p10) & is.finite(p90) &
        v2_median >= p10 & v2_median <= p90
    )

    # Scaled by this run's own spread, so a large coefficient
    # with a large spread is not flagged for a large difference.
    spread <- with(joined, (p90 - p10) / 2)
    joined$standardized_difference <- with(
      joined,
      ifelse(
        is.finite(spread) & spread > 0,
        abs(median - v2_median) / spread,
        NA_real_
      )
    )

    parity_rows[[label]] <- joined
  }
}

# 4. Write ----
parity <- do.call(rbind, parity_rows)

if (!is.null(parity)) {
  rownames(parity) <- NULL
  data.table::fwrite(
    parity, file.path(tables_dir, "parity_climate.csv"), na = ""
  )

  parity_summary <- do.call(rbind, lapply(
    split(parity, list(parity$taxon, parity$region), drop = TRUE),
    function(block) {
      matched <- block[is.finite(block$v2_median), ]

      if (is.null(matched$age_spline_term)) {
        matched$age_spline_term <- FALSE
      }

      reachable <- matched[!matched$age_spline_term, ]

      data.frame(
        taxon = block$taxon[1],
        region = block$region[1],
        terms_compared = nrow(matched),
        species = length(unique(matched$species)),
        in_band_pct = round(
          100 * mean(matched$in_band, na.rm = TRUE), 1
        ),
        # The share the harness actually implements, which is
        # the number the gate should be read on.
        reachable_terms = nrow(reachable),
        reachable_in_band_pct = round(
          100 * mean(reachable$in_band, na.rm = TRUE), 1
        ),
        median_standardized_difference = round(
          stats::median(
            reachable$standardized_difference, na.rm = TRUE
          ), 3
        ),
        stringsAsFactors = FALSE
      )
    }
  ))

  rownames(parity_summary) <- NULL
  data.table::fwrite(
    parity_summary,
    file.path(tables_dir, "parity_summary.csv"), na = ""
  )

  cat("\nClimate-stage parity:\n")
  print(parity_summary)
} else {
  cat("\nNo parity comparison produced.\n")
}

for (note in notes) {
  cat("  note: ", note, "\n", sep = "")
}

